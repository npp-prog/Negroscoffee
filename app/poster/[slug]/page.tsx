import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { ArrowLeft, Star } from "lucide-react";
import QRCode from "qrcode";

import { PrintButton } from "./print-button";
import { getPrerenderSlugs, getPublicShop } from "@/app/shop/[slug]/data";
import { Logo } from "@/components/brand/logo";
import { PRICE_TIER_META, SHOP_TYPE_META } from "@/lib/categories";
import { siteUrl } from "@/lib/site";

export async function generateStaticParams() {
  return getPrerenderSlugs();
}

export async function generateMetadata({ params }: PageProps<"/poster/[slug]">): Promise<Metadata> {
  const { slug } = await params;
  const shop = await getPublicShop(slug);
  return { title: shop ? `${shop.name} poster` : "Poster", robots: { index: false } };
}

/** Printable "Find us on Kape Negros" poster with a QR code to the shop page. */
export default async function PosterPage({ params }: PageProps<"/poster/[slug]">) {
  const { slug } = await params;
  const shop = await getPublicShop(slug);
  if (!shop) notFound();
  const url = `${siteUrl()}/shop/${shop.slug}`;
  // SVG markup generated by the qrcode library from our own URL (no user HTML).
  const qr = await QRCode.toString(url, {
    type: "svg",
    margin: 0,
    errorCorrectionLevel: "M",
    color: { dark: "#2B1D14", light: "#FFFFFF" },
  });
  const tier = PRICE_TIER_META[shop.priceTier];
  const host = url.replace(/^https?:\/\//, "");

  return (
    <main className="min-h-dvh bg-background px-4 py-6 print:bg-white print:p-0">
      <style>{`@page { size: A4 portrait; margin: 12mm; }`}</style>
      <div className="mx-auto mb-4 flex max-w-[640px] items-center justify-between gap-3 print:hidden">
        <Link
          href={`/shop/${shop.slug}`}
          className="inline-flex min-h-11 items-center gap-1.5 text-sm text-muted-foreground hover:text-foreground"
        >
          <ArrowLeft className="size-4" aria-hidden="true" /> Shop page
        </Link>
        <PrintButton />
      </div>
      <p className="mx-auto mb-4 max-w-[640px] text-[13px] text-muted-foreground print:hidden">
        Print it on A4 (or save as PDF) and put it on your counter, door or menu. Customers scan the
        code to see your menu prices, hours and directions, and to leave a review.
      </p>
      <article className="mx-auto flex aspect-[210/297] max-w-[640px] flex-col items-center justify-between rounded-[20px] border-[6px] border-[#C8893B] bg-white p-[7%] text-center text-[#2B1D14] shadow-float print:max-w-none print:rounded-none print:shadow-none">
        <div className="flex flex-col items-center gap-3">
          <Logo className="text-[#2B1D14] [&_svg]:size-10" />
          <p className="font-display text-[clamp(1.5rem,5vw,2.25rem)] leading-tight font-semibold">
            Find us on Kape Negros
          </p>
        </div>
        <div className="flex w-full flex-col items-center gap-4">
          <h1 className="font-display text-[clamp(2rem,8vw,3.75rem)] leading-[1.05] font-semibold text-balance">
            {shop.name}
          </h1>
          <p className="text-[clamp(0.9rem,2.6vw,1.15rem)] text-[#7A6758]">
            {SHOP_TYPE_META[shop.type].label} · {tier.symbol} {tier.label}
            {shop.cityName ? ` · ${shop.cityName}` : ""}
          </p>
        </div>
        <div className="flex w-full flex-col items-center gap-3">
          <div
            role="img"
            aria-label={`QR code linking to ${url}`}
            className="aspect-square w-[58%] rounded-2xl border-2 border-[#E7DED3] bg-white p-[4%] [&_svg]:size-full"
            dangerouslySetInnerHTML={{ __html: qr }}
          />
          <p className="text-[clamp(1rem,3vw,1.35rem)] font-semibold">
            Scan for menu prices, hours &amp; directions
          </p>
          <p className="inline-flex items-center gap-1.5 text-[clamp(0.85rem,2.4vw,1.05rem)] text-[#7A6758]">
            <Star className="size-4 fill-[#C8893B] text-[#C8893B]" aria-hidden="true" />
            Enjoyed your cup? Leave us a review!
          </p>
        </div>
        <p className="text-[clamp(0.7rem,2vw,0.9rem)] break-all text-[#7A6758]">{host}</p>
      </article>
    </main>
  );
}
